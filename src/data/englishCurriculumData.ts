// Helper to convert an English phrase or word into standard KanaSegment array
function buildEnglishSegments(word: string): KanaSegment[] {
  return word.split("").map((char) => {
    const isSpace = char === " ";
    return {
      kana: char,
      romaji: isSpace ? [" ", "-"] : [char.toLowerCase()],
      displayRomaji: isSpace ? "␣" : char,
    };
  });
}

